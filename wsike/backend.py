"""strongSwan (swanctl/charon-systemd), XFRM interface, policy routing and DNS.

Design (route-based IPsec, similar to how wg-quick works):

* An XFRM interface `wsike0` is bound to the SAs via if_id, so tunnel traffic is
  ordinary routed traffic through a real interface (easy to firewall).
* charon's IKE sockets carry FWMARK (strongswan.d/wsike.conf) and the ESP outer
  packets get FWMARK through `set_mark_out`. Policy rules send marked packets
  to the main table and everything else to a table whose default route is
  wsike0. That keeps working across Wi-Fi/Ethernet changes.
* DNS from the VPN is put on wsike0 in systemd-resolved with the `~.` routing
  domain so every lookup is sent through the tunnel.
"""

import os
import re
import shutil
import time

from . import netutil
from .common import (CONN_NAME, FWMARK, IF_ID, IFACE, ROUTE_TABLE, RULE_PRIO_EXCLUDE,
                     RULE_PRIO_FWMARK, RULE_PRIO_SUPPRESS, RULE_PRIO_TUNNEL)
from .netutil import run

# Must live under /etc/swanctl: Ubuntu's AppArmor profile for swanctl only
# allows reading files there (anything else is silently skipped).
SWANCTL_CONF = "/etc/swanctl/conf.d/wsike.conf"
RESOLV_BACKUP = "/run/wsike/resolv.conf.backup"
RULE_PRIO_SERVER = 5745
RULE_PRIO_DNS = 5749
IKE_PROPOSALS = ("aes256gcm16-prfsha384-ecp384, aes256gcm16-prfsha256-ecp256, aes256-sha256-modp2048, "
                 "aes256-sha256-ecp256, aes256-sha1-modp2048, aes256-sha1-modp1024, aes128-sha1-modp1024, default")
ESP_PROPOSALS = "aes256gcm16, aes256-sha256, aes256-sha1, aes128-sha1, default"


def _swan_str(value):
    """Quote a value for swanctl.conf."""
    if any(c in value for c in "\n\r\0"):
        raise ValueError("credentials must not contain line breaks")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def friendly_error(output):
    """Map charon/swanctl output of a failed initiate to a user-facing message.

    Only match failure markers: lines like "authentication of ... with EAP"
    appear in every attempt and must not be mistaken for a failure.
    """
    o = output.lower()
    if ("eap_failure" in o or "eap authentication failed" in o or "authentication_failed" in o
            or re.search(r"eap method \S+ failed", o)):
        return ("Authentication failed. Use the IKEv2 username/password from Windscribe's "
                "IKEv2 config generator (they are not your Windscribe login).")
    if ("constraint check failed" in o or "no trusted" in o or "no issuer certificate" in o
            or re.search(r"authentication of '[^']*' with \S+ failed", o)):
        return "Server certificate could not be verified (check the server hostname and the CA certificates)."
    if "no_proposal_chosen" in o:
        return "Server rejected all encryption proposals."
    if "ts_unacceptable" in o:
        return "Server rejected the requested traffic selectors."
    if "giving up after" in o or "initiate failed: timeout" in o or "timed out" in o:
        return "Server did not respond (UDP 500/4500 blocked or server down)."
    if "vici" in o and ("no such file" in o or "connection refused" in o):
        return "strongSwan (charon) is not running."
    lines = [l for l in output.strip().splitlines() if l.strip()]
    return lines[-1] if lines else "connection failed"


class StrongSwanBackend:
    def __init__(self, log):
        self.log = log
        self.server_ip = None
        self.dns_servers = []
        self.routing = ("off", ())      # (split_mode, split_v4) of the current tunnel

    # ------------------------------------------------------------------ helpers
    def ensure_charon(self):
        for unit in ("strongswan.service", "strongswan-swanctl.service"):
            p = run(["systemctl", "start", unit], check=False)
            if p.returncode == 0:
                break
        else:
            raise RuntimeError("could not start strongSwan (install the charon-systemd package)")
        for _ in range(50):
            if os.path.exists("/run/charon.vici") or os.path.exists("/var/run/charon.vici"):
                return
            time.sleep(0.1)
        raise RuntimeError("strongSwan vici socket did not appear")

    def write_config(self, hostname, server_ip, username, password):
        os.makedirs(os.path.dirname(SWANCTL_CONF), exist_ok=True)
        conf = f"""# generated by wsike - do not edit
connections {{
  {CONN_NAME} {{
    version = 2
    remote_addrs = {server_ip}
    vips = 0.0.0.0
    encap = yes
    mobike = yes
    fragmentation = yes
    keyingtries = 1
    dpd_delay = 20s
    proposals = {IKE_PROPOSALS}
    local {{
      auth = eap-mschapv2
      eap_id = {_swan_str(username)}
    }}
    remote {{
      auth = pubkey
      id = {_swan_str(hostname)}
    }}
    children {{
      {CONN_NAME} {{
        local_ts = dynamic
        remote_ts = 0.0.0.0/0
        if_id_in = 0x{IF_ID:x}
        if_id_out = 0x{IF_ID:x}
        set_mark_out = 0x{FWMARK:x}
        esp_proposals = {ESP_PROPOSALS}
        dpd_action = restart
        start_action = none
        close_action = none
        rekey_time = 1h
      }}
    }}
  }}
}}
secrets {{
  eap-{CONN_NAME} {{
    id = {_swan_str(username)}
    secret = {_swan_str(password)}
  }}
}}
"""
        fd = os.open(SWANCTL_CONF, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(conf)

    def load_config(self):
        p = run(["swanctl", "--load-all", "--noprompt"], check=False)
        out = (p.stdout + p.stderr).strip()
        for line in out.splitlines():
            if "plugin" not in line:
                self.log("swanctl: " + line)
        conns = run(["swanctl", "--list-conns"], check=False).stdout
        if not re.search(rf"^{CONN_NAME}:", conns, re.M):
            raise RuntimeError("strongSwan did not accept the generated connection config "
                               f"({SWANCTL_CONF}); see the debug log")

    def setup_iface(self):
        if netutil.iface_exists(IFACE):
            run(["ip", "link", "del", IFACE], check=False)
        p = run(["ip", "link", "add", IFACE, "type", "xfrm", "if_id", hex(IF_ID)], check=False)
        if p.returncode != 0:
            _, dev = netutil.default_route()
            run(["ip", "link", "add", IFACE, "type", "xfrm", "dev", dev or "lo", "if_id", hex(IF_ID)])
        run(["ip", "link", "set", IFACE, "mtu", "1400", "up"])
        run(["ip", "-6", "addr", "flush", "dev", IFACE], check=False)
        for key, val in (("net.ipv4.conf.all.src_valid_mark", "1"),
                         (f"net.ipv6.conf.{IFACE}.disable_ipv6", "1"),
                         (f"net.ipv4.conf.{IFACE}.rp_filter", "2")):
            run(["sysctl", "-q", "-w", f"{key}={val}"], check=False)

    def _rule(self, *args, prio):
        run(["ip", "-4", "rule", "add", *args, "priority", str(prio)])

    def _flush_rules(self):
        for prio in (RULE_PRIO_EXCLUDE, RULE_PRIO_SERVER, RULE_PRIO_DNS, RULE_PRIO_FWMARK,
                     RULE_PRIO_SUPPRESS, RULE_PRIO_TUNNEL):
            for _ in range(512):
                if run(["ip", "-4", "rule", "del", "priority", str(prio)], check=False).returncode:
                    break
        run(["ip", "-4", "route", "flush", "table", str(ROUTE_TABLE)], check=False)

    # --------------------------------------------------------------- lifecycle
    def connect(self, hostname, username, password, *, split_mode="off", split_v4=(),
                custom_dns=(), timeout=30):
        """Bring the tunnel up. Returns dict with server_ip, vip, dns."""
        ips = netutil.resolve(hostname)
        self.server_ip = ips[0]
        self.log(f"{hostname} resolved to {', '.join(ips)}; using {self.server_ip}")
        self.ensure_charon()
        self.write_config(hostname, self.server_ip, username, password)
        self.setup_iface()
        self.load_config()
        self.log("initiating IKEv2 SA")
        p = run(["swanctl", "--initiate", "--ike", CONN_NAME, "--child", CONN_NAME,
                 "--timeout", str(timeout)], check=False, timeout=timeout + 10)
        for line in (p.stdout + p.stderr).splitlines()[-30:]:
            if "plugin" not in line:
                self.log("charon: " + line)
        if p.returncode != 0 or not self.is_up():
            raise RuntimeError(friendly_error(p.stdout + p.stderr))
        vip = netutil.iface_ipv4(IFACE)
        self.log(f"tunnel established, virtual IP {vip}")
        self.setup_routing(split_mode, split_v4)
        self.setup_dns(custom_dns)
        return {"server_ip": self.server_ip, "vip": vip, "dns": self.dns_servers}

    def setup_routing(self, split_mode, split_v4):
        self.routing = (split_mode, tuple(split_v4))
        self._flush_rules()
        if split_mode == "inclusive":
            for net in split_v4:
                run(["ip", "-4", "route", "replace", net, "dev", IFACE, "table", str(ROUTE_TABLE)])
        else:
            run(["ip", "-4", "route", "replace", "default", "dev", IFACE, "table", str(ROUTE_TABLE)])
            if split_mode == "exclusive":
                for net in split_v4:
                    self._rule("to", net, "lookup", "main", prio=RULE_PRIO_EXCLUDE)
        self._rule("to", f"{self.server_ip}/32", "lookup", "main", prio=RULE_PRIO_SERVER)
        self._rule("fwmark", hex(FWMARK), "lookup", "main", prio=RULE_PRIO_FWMARK)
        self._rule("lookup", "main", "suppress_prefixlength", "0", prio=RULE_PRIO_SUPPRESS)
        self._rule("lookup", str(ROUTE_TABLE), prio=RULE_PRIO_TUNNEL)
        run(["ip", "-4", "route", "flush", "cache"], check=False)

    def _pushed_dns(self):
        p = run(["resolvectl", "dns", IFACE], check=False)
        found = re.findall(r"\d+\.\d+\.\d+\.\d+", p.stdout.split(":", 1)[-1])
        return [ip for ip in found if ip != netutil.iface_ipv4(IFACE)]

    def setup_dns(self, custom_dns=()):
        servers = list(custom_dns)
        if not servers:
            for _ in range(20):          # resolve plugin may still be writing
                servers = self._pushed_dns()
                if servers:
                    break
                time.sleep(0.1)
        if not servers:
            self.log("VPN pushed no DNS server; falling back to 1.1.1.1 through the tunnel")
            servers = ["1.1.1.1"]
        self.dns_servers = servers
        for _ in range(64):              # idempotent: drop rules from a previous call
            if run(["ip", "-4", "rule", "del", "priority", str(RULE_PRIO_DNS)], check=False).returncode:
                break
        # Make sure DNS servers are always reached through the tunnel, even when
        # they sit inside a range that also exists on the LAN.
        for ip in servers:
            run(["ip", "-4", "route", "replace", f"{ip}/32", "dev", IFACE, "table", str(ROUTE_TABLE)])
            self._rule("to", f"{ip}/32", "lookup", str(ROUTE_TABLE), prio=RULE_PRIO_DNS)

        resolved = "systemd/resolve" in os.path.realpath("/etc/resolv.conf") and shutil.which("resolvectl")
        if resolved:
            run(["resolvectl", "dns", IFACE, *servers])
            run(["resolvectl", "domain", IFACE, "~."])
            run(["resolvectl", "default-route", IFACE, "yes"], check=False)
            run(["resolvectl", "dnsovertls", IFACE, "no"], check=False)
            run(["resolvectl", "llmnr", IFACE, "no"], check=False)
            run(["resolvectl", "mdns", IFACE, "no"], check=False)
            run(["resolvectl", "flush-caches"], check=False)
        else:
            os.makedirs(os.path.dirname(RESOLV_BACKUP), exist_ok=True)
            if not os.path.exists(RESOLV_BACKUP):
                shutil.copy2("/etc/resolv.conf", RESOLV_BACKUP, follow_symlinks=True)
            target = os.path.realpath("/etc/resolv.conf")
            with open(target, "w") as f:
                f.write("# written by wsike while the VPN is connected\n")
                f.write("".join(f"nameserver {ip}\n" for ip in servers))
        self.log(f"DNS ({'resolved' if resolved else 'resolv.conf'}): {', '.join(servers)}")

    def restore_dns(self):
        if netutil.iface_exists(IFACE):
            run(["resolvectl", "revert", IFACE], check=False)
        if os.path.exists(RESOLV_BACKUP):
            shutil.copy2(RESOLV_BACKUP, os.path.realpath("/etc/resolv.conf"))
            os.unlink(RESOLV_BACKUP)
        run(["resolvectl", "flush-caches"], check=False)
        self.dns_servers = []

    def disconnect(self):
        if shutil.which("swanctl"):
            run(["swanctl", "--terminate", "--ike", CONN_NAME, "--force", "--timeout", "5"],
                check=False, timeout=20)
        self.restore_dns()
        self._flush_rules()
        if netutil.iface_exists(IFACE):
            run(["ip", "link", "del", IFACE], check=False)
        self.server_ip = None

    def abort(self):
        """Tear down the IKE_SA right away; makes a pending initiate return."""
        if shutil.which("swanctl"):
            run(["swanctl", "--terminate", "--ike", CONN_NAME, "--force", "--timeout", "2"],
                check=False, timeout=10)

    def reinitiate(self, custom_dns=(), timeout=15):
        """Re-establish a dropped SA on the existing interface/routing.

        Returns the new {"vip", "dns"} or None. The old SA's teardown made
        charon remove its DNS settings from wsike0, so DNS is applied again.
        """
        p = run(["swanctl", "--initiate", "--ike", CONN_NAME, "--child", CONN_NAME,
                 "--timeout", str(timeout)], check=False, timeout=timeout + 10)
        if p.returncode != 0 or not self.is_up():
            return None
        # When charon removed the virtual IP of the old SA, the kernel flushed
        # every route through wsike0, so the routing has to be rebuilt.
        self.setup_routing(*self.routing)
        self.setup_dns(custom_dns)
        return {"vip": netutil.iface_ipv4(IFACE), "dns": self.dns_servers}

    def routes_ok(self):
        """True when the tunnel routing table still has its routes."""
        split_mode, split_v4 = self.routing
        p = run(["ip", "-4", "route", "show", "table", str(ROUTE_TABLE)], check=False)
        if split_mode == "inclusive":
            return all(net.split("/")[0] in p.stdout for net in split_v4)
        return p.stdout.startswith("default ") or "\ndefault " in p.stdout

    def repair_routes(self, custom_dns=()):
        self.log("tunnel routes were missing; restoring them")
        self.setup_routing(*self.routing)
        self.setup_dns(custom_dns)

    def is_up(self):
        p = run(["swanctl", "--list-sas", "--ike", CONN_NAME], check=False, timeout=10)
        return "ESTABLISHED" in p.stdout and "INSTALLED" in p.stdout
